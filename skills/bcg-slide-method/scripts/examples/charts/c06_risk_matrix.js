// c06_risk_matrix.js リスクマトリクス(手本): リスクごとの「起きる確率 × 1株価値への影響」を L.bubbleMatrix で描く。
// 円の面積 = 期待損失(確率 × 影響)。右上(確率も影響も大きい)を赤く塗り、監視の順番を ①②③ で示す。数字は手本用の固定値(架空の会社)
module.exports = function build(pres, L) {
  const s = L.contentSlide(pres, {
    source: '手本用の固定値(架空の化学メーカー)。確率は過去10年の同業の発生回数(基準率)から、影響は価値評価の計算機で理論株価を動かした差',
  });
  L.paneHead(s, 0.5, 1.62, 7.9, 'リスクマトリクス: 横 = 5年以内に起きる確率、縦 = 理論株価への影響(%)、円 = 期待損失', 'pane_rm_head');
  L.bubbleMatrix(s, {
    xTitle: '5年以内に起きる確率(%)', yTitle: '起きたときの理論株価の下落(%)',
    xMin: 0, xMax: 60, xTicks: [0, 20, 40, 60], xFmt: v => v + '%',
    yMin: 0, yMax: 35, yTicks: [0, 10, 20, 30], yFmt: v => (v ? '−' : '') + v + '%',
    xSplit: 25, ySplit: 12,
    quad: { tl: '稀だが重い(兆候を監視)', tr: '最優先: 起きやすく重い', bl: '許容', br: '起きやすいが軽い' },
    hot: 'tr',
    sizeMax: 0.9, sizeLegend: '円の面積 = 期待損失(確率 × 下落率)',
    items: [
      { label: '原料価格の高騰', sub: '40% × −18%', x: 40, y: 18, size: 7.2, tone: 'risk', n: 1 },
      { label: '価格競争', sub: '30% × −22%', x: 30, y: 22, size: 6.6, tone: 'risk', n: 2, lpos: 'l' },
      { label: '大口顧客の離脱', sub: '15% × −30%', x: 18, y: 29, size: 4.5, tone: 'amber', n: 3 },
      { label: '増設の遅れ', sub: '35% × −8%', x: 35, y: 8, size: 2.8, tone: 'muted' },
      { label: '為替', sub: '50% × −4%', x: 50, y: 4, size: 2.0, tone: 'muted' },
      { label: '規制の強化', sub: '10% × −12%', x: 10, y: 12, size: 1.2, tone: 'muted', lpos: 'b' },
    ],
  }, { x: 0.5, y: 2.12, w: 7.9, h: 4.05, name: 'rm' });
  L.lookBox(s, [
    { n: 1, text: '原料高は確率40%・下落18%で期待損失が最大。\n兆候: ナフサが四半期で+20%超' },
    { n: 2, text: '価格競争は中国の増設(2027年稼働)が契機。\n兆候: 主力品の単価が2四半期続けて下落' },
    { n: 3, text: '大口顧客の離脱は確率15%でも下落30%と重い。\n上位3社で売上の35%を占めるため' },
  ], { x: 8.65, y: 1.98, w: 4.18, h: 3.0 });
  L.takeaway(s, 8.65, 5.12, 4.18, 1.05,
    '期待損失の上位2つ(原料高・価格競争)は\nどちらも粗利率に出る。監視は粗利率に絞る', { fontSize: 10 });
  L.termNotes(s, [
    { term: '期待損失', plain: '起きる確率 × 起きたときの下落率', why: '確率と重さを1つの物差しにして、監視の順番を決めるため' },
    { term: '基準率', plain: '同じ条件で過去に何回中何回起きたか', why: '確率を気分でなく実績から置くため' },
  ], { x: 0.5, y: 6.28, w: 12.33 });
};
